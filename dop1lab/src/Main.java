/*
 * Доп. лабораторная работа № 1. Рекурсия и головоломки.
 * Вариант 17. Головоломка «Нумератор» (Numbrix).
 * Нужно заполнить пустые клетки поля числами от 1 до (число клеток) так, чтобы:
 * 1) каждое число встречалось ровно один раз;
 * 2) числа шли подряд: рядом с числом k стоит число k + 1
 *    (сверху, снизу, слева или справа; по диагонали переходить нельзя).
 * Некоторые числа уже стоят в клетках (они даны в условии).
 */
public class Main {
    // Точка входа программы. Аргумент args не используется.
    // Решает три головоломки: обычную, с несколькими решениями и без решения.
    public static void main(String[] args) {
        System.out.println("Доп. лабораторная № 1. Рекурсия и головоломки. Нумератор.");
        System.out.println("Обозначения: '.' — пустая клетка, число — клетка, заполненная заранее.");

        // Головоломка 1: поле 5 x 5, решение единственное.
        String[] puzzle1 = {
            "19  .  .  . 25",
            "18  . 16  .  .",
            " .  .  .  .  .",
            " .  1  .  . 12",
            " 5  .  .  .  ."
        };
        solvePuzzle("Головоломка 1 (5 x 5)", puzzle1);

        // Головоломка 2: поле 3 x 3, даны только 1 и 9 в противоположных углах.
        // Путь от 1 до 9 можно проложить по-разному, поэтому решений несколько.
        String[] puzzle2 = {
            "1 . .",
            ". . .",
            ". . 9"
        };
        solvePuzzle("Головоломка 2 (3 x 3, даны только 1 и 9)", puzzle2);

        // Головоломка 3: 1 и 9 стоят в соседних клетках, хотя между ними должно быть 8 шагов.
        // Каждый шаг меняет «цвет» клетки на шахматной доске, а у соседних клеток цвета разные:
        // после чётного числа шагов мы попадаем в клетку того же цвета. Решений нет.
        String[] puzzle3 = {
            "1 9 .",
            ". . .",
            ". . ."
        };
        solvePuzzle("Головоломка 3 (1 и 9 рядом, невыполнимо)", puzzle3);
    }

    // Печатает условие, решает головоломку и печатает результат.
    // title — название головоломки; lines — поле в виде строк текста.
    private static void solvePuzzle(String title, String[] lines) {
        System.out.println("\n===== " + title + " =====");
        Board board = new Board(lines);

        System.out.println("Условие:");
        board.print(null);

        int count = NumbrixSolver.solve(board);
        System.out.println("\nЧисло решений: " + count);
        System.out.println("Рекурсивных вызовов: " + NumbrixSolver.getStepCount());

        if (count == 0) {
            System.out.println("У этой головоломки нет решения.");
        } else {
            System.out.println("Первое найденное решение:");
            board.print(NumbrixSolver.getFirstSolution());
        }
    }
}
