/*
 * Доп. лабораторная работа № 1. Рекурсия и головоломки.
 * Вариант 9. Головоломка «Фонари» (Light Up).
 * Нужно поставить лампы в белые клетки так, чтобы:
 * 1) было освещено всё поле (свет идёт по строке и столбцу до чёрной клетки);
 * 2) лампы не освещали друг друга;
 * 3) число в чёрной клетке равнялось числу ламп в соседних с ней клетках
 *    (сверху, снизу, слева, справа; по диагонали не считаем).
 */
public class Main {
    // Точка входа программы. Аргумент args не используется.
    // Решает три головоломки: обычную, с несколькими решениями и без решения.
    public static void main(String[] args) {
        System.out.println("Доп. лабораторная № 1. Рекурсия и головоломки. Фонари.");
        System.out.println("Обозначения: '.' белая клетка, '#' чёрная клетка без числа,");
        System.out.println("цифра — чёрная клетка с числом, L — лампа.");

        // Головоломка 1: поле 7 x 7, решение единственное.
        String[] puzzle1 = {
            "....1.0",
            "1#.....",
            "....2..",
            "......1",
            ".00.#..",
            ".#0..#.",
            "......2"
        };
        solvePuzzle("Головоломка 1 (7 x 7)", puzzle1);

        // Головоломка 2: пустое поле 2 x 2. Лампы должны стоять по диагонали,
        // а диагоналей две, поэтому решений два.
        String[] puzzle2 = {
            "..",
            ".."
        };
        solvePuzzle("Головоломка 2 (2 x 2, без чисел)", puzzle2);

        // Головоломка 3: число 4 в верхней строке, но у этой клетки всего три соседа
        // (сверху поля нет), поэтому четыре лампы рядом поставить нельзя. Решений нет.
        String[] puzzle3 = {
            ".4.",
            "..."
        };
        solvePuzzle("Головоломка 3 (число 4 невыполнимо)", puzzle3);
    }

    // Печатает условие, решает головоломку и печатает результат.
    // title — название головоломки; lines — поле в виде строк текста.
    private static void solvePuzzle(String title, String[] lines) {
        System.out.println("\n===== " + title + " =====");
        Board board = new Board(lines);

        System.out.println("Условие:");
        board.print(null);

        int count = LightUpSolver.solve(board);
        System.out.println("\nЧисло решений: " + count);
        System.out.println("Рекурсивных вызовов: " + LightUpSolver.getStepCount());

        if (count == 0) {
            System.out.println("У этой головоломки нет решения.");
        } else {
            System.out.println("Первое найденное решение:");
            board.print(LightUpSolver.getFirstSolution());
        }
    }
}
